"""Turn labelled drone videos (Anti-UAV-RGBT layout) into a YOLO detection dataset.

Run:  python -m src.training.prepare_drone_dataset

Input layout (one folder per clip):
    data/raw/anti_uav_rgbt/<split>/<clip>/visible.mp4
    data/raw/anti_uav_rgbt/<split>/<clip>/visible.json   {"exist": [0|1, ...], "gt_rect": [[x, y, w, h], ...]}

Output (Ultralytics layout, one class "drone"):
    data/processed/drone_yolo/images/{train,val}/<clip>_<frame>.jpg
    data/processed/drone_yolo/labels/{train,val}/<clip>_<frame>.txt
    data/drone_dataset.yaml

Clips are split into train/val as whole clips, so no video appears in both. Every
``stride``-th frame is kept (neighbouring frames are near-duplicates). Frames where the drone
is absent are kept as negatives with an empty label file.
"""

import argparse
import json
import random
from pathlib import Path
from typing import List, Union

import cv2


def _clips(root: Path) -> List[Path]:
    return sorted(p.parent for p in root.rglob("visible.mp4") if (p.parent / "visible.json").is_file())


def _yolo_line(rect, w: int, h: int) -> str:
    x, y, bw, bh = (float(v) for v in rect)
    x0, y0 = max(0.0, x), max(0.0, y)
    x1, y1 = min(float(w), x + bw), min(float(h), y + bh)
    if x1 - x0 < 2 or y1 - y0 < 2:
        return ""
    return f"0 {(x0 + x1) / 2 / w:.6f} {(y0 + y1) / 2 / h:.6f} {(x1 - x0) / w:.6f} {(y1 - y0) / h:.6f}\n"


def prepare(
    src: Union[str, Path] = "data/raw/anti_uav_rgbt",
    out: Union[str, Path] = "data/processed/drone_yolo",
    yaml_path: Union[str, Path] = "data/drone_dataset.yaml",
    stride: int = 10,
    val_share: float = 0.2,
    seed: int = 0,
) -> None:
    src, out = Path(src), Path(out)
    clips = _clips(src)
    if not clips:
        raise FileNotFoundError(f"No <clip>/visible.mp4 + visible.json found under {src}")
    random.Random(seed).shuffle(clips)
    n_val = max(1, round(len(clips) * val_share))
    split_of = {c: ("val" if i < n_val else "train") for i, c in enumerate(clips)}

    counts = {"train": [0, 0], "val": [0, 0]}  # [images, images with a drone]
    for n, clip in enumerate(sorted(clips), 1):
        split = split_of[clip]
        (out / "images" / split).mkdir(parents=True, exist_ok=True)
        (out / "labels" / split).mkdir(parents=True, exist_ok=True)
        ann = json.loads((clip / "visible.json").read_text(encoding="utf-8"))
        exist, rects = ann.get("exist", []), ann.get("gt_rect", [])
        cap = cv2.VideoCapture(str(clip / "visible.mp4"))
        i = 0
        while True:
            ok, frame = cap.read()
            if not ok or i >= len(rects):
                break
            if i % stride == 0:
                h, w = frame.shape[:2]
                present = bool(exist[i]) if i < len(exist) else bool(rects[i])
                line = _yolo_line(rects[i], w, h) if present and rects[i] and len(rects[i]) == 4 else ""
                stem = f"{clip.name}_{i:05d}"
                cv2.imwrite(str(out / "images" / split / f"{stem}.jpg"), frame, [cv2.IMWRITE_JPEG_QUALITY, 92])
                (out / "labels" / split / f"{stem}.txt").write_text(line, encoding="utf-8")
                counts[split][0] += 1
                counts[split][1] += bool(line)
            i += 1
        cap.release()
        print(f"[{n}/{len(clips)}] {clip.name} -> {split}", flush=True)

    Path(yaml_path).write_text(
        f"# Generated by src/training/prepare_drone_dataset.py from {src.as_posix()}\n"
        f"path: {out.resolve().as_posix()}\n"
        "train: images/train\n"
        "val: images/val\n"
        "names:\n  0: drone\n",
        encoding="utf-8",
    )
    for s, (imgs, pos) in counts.items():
        clips_in = sum(1 for v in split_of.values() if v == s)
        print(f"{s}: {clips_in} clips, {imgs} images ({pos} with a drone, {imgs - pos} empty)")
    print(f"Dataset YAML -> {yaml_path}")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--src", default="data/raw/anti_uav_rgbt")
    p.add_argument("--out", default="data/processed/drone_yolo")
    p.add_argument("--yaml", default="data/drone_dataset.yaml")
    p.add_argument("--stride", type=int, default=10, help="keep every Nth frame")
    p.add_argument("--val-share", type=float, default=0.2, help="share of clips held out for validation")
    p.add_argument("--seed", type=int, default=0)
    a = p.parse_args()
    prepare(a.src, a.out, a.yaml, a.stride, a.val_share, a.seed)


if __name__ == "__main__":
    main()
